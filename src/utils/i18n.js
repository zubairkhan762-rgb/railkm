export function isSupportedLang(code) {
	return typeof code === 'string' && Object.prototype.hasOwnProperty.call(DICT, code);
}

/**
 * A language is offered in the picker only when its dictionary covers every
 * English key. This keeps partially translated languages from silently
 * falling back to English mid-interface.
 */
export function isLangComplete(code) {
	const table = DICT[code];
	if (!table) return false;
	return Object.keys(DICT[DEFAULT_LANG]).every((key) => Object.prototype.hasOwnProperty.call(table, key));
}

export const AVAILABLE_LANGUAGES = LANGUAGES.filter(({ code }) => isLangComplete(code));

export function getLang() {
	if (typeof localStorage === 'undefined') return DEFAULT_LANG;
	try {
		const stored = localStorage.getItem(LANG_KEY);
		if (isSupportedLang(stored)) return stored;
	} catch {
		/* storage unavailable (private mode) — fall back to the default */
	}
	return DEFAULT_LANG;
}

export function setLang(code) {
	const next = isSupportedLang(code) ? code : DEFAULT_LANG;
	try {
		localStorage.setItem(LANG_KEY, next);
	} catch {
		/* storage unavailable (private mode) — session-only switch */
	}
	return next;
}

export function t(key, vars = {}, lang = getLang()) {
	const table = DICT[lang] || DICT[DEFAULT_LANG];
	let value = table[key] ?? DICT[DEFAULT_LANG][key] ?? key;
	if (vars && typeof value === 'string') {
		for (const [name, replacement] of Object.entries(vars)) {
			value = value.split(`{${name}}`).join(String(replacement));
		}
	}
	return value;
}
